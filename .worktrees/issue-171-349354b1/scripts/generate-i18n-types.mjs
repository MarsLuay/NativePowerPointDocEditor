import fs from 'node:fs';
import path from 'node:path';
import {
	PROJECT_ROOT,
	EN_LOCALE_DIR,
	collectMessageKeys,
	readLocaleCatalog,
} from './lib/i18n-utils.mjs';

const OUTPUT_PATH = path.join(PROJECT_ROOT, 'src/i18n/generated/messageKeys.generated.ts');

function escapeTypeLiteral(key) {
	return key.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function formatMessageKeyType(keys) {
	if (keys.length === 0) {
		return 'never';
	}

	return keys.map((key) => `'${escapeTypeLiteral(key)}'`).join(' | ');
}

function formatMessageKeysArray(keys) {
	if (keys.length === 0) {
		return '[] as const';
	}

	const lines = keys.map((key) => `\t'${escapeTypeLiteral(key)}',`);
	return `[\n${lines.join('\n')}\n] as const`;
}

function main() {
	const catalog = readLocaleCatalog(EN_LOCALE_DIR);
	const keys = collectMessageKeys(catalog);
	const messageKeyType = formatMessageKeyType(keys);
	const messageKeysArray = formatMessageKeysArray(keys);

	const output = `// Auto-generated by scripts/generate-i18n-types.mjs. Do not edit.

export type MessageKey = ${messageKeyType};

export const MESSAGE_KEYS = ${messageKeysArray};
`;

	fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
	fs.writeFileSync(OUTPUT_PATH, output, 'utf8');

	console.log(`Wrote ${path.relative(PROJECT_ROOT, OUTPUT_PATH)} (${keys.length} keys).`);
}

main();
